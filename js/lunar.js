  function monthDays(info, m) { return (info & (0x10000 >> m)) ? 30 : 29; }
  function leapMonth(info) { return info & 0xf; }
  function leapDays(info) { return leapMonth(info) ? ((info & 0x10000) ? 30 : 29) : 0; }

  function yearDays(info) {
    var sum = 0;
    for (var m = 1; m <= 12; m++) sum += monthDays(info, m);
    return sum + leapDays(info);
  }

  /**
   * 國曆轉農曆
   * @return { year, month, day, leap } 或超出範圍時回傳 null
   */
  function fromSolar(year, month, day) {
    var offset = Math.round((Date.UTC(year, month - 1, day) - FIRST_NEW_YEAR) / 86400000);
    if (offset < 0) return null;

    for (var i = 0; i < INFO.length; i++) {
      var yd = yearDays(INFO[i]);
      if (offset < yd) {
        var info = INFO[i];
        var leap = leapMonth(info);
        for (var m = 1; m <= 12; m++) {
          var md = monthDays(info, m);
          if (offset < md) return { year: FIRST_YEAR + i, month: m, day: offset + 1, leap: false };
          offset -= md;
          if (m === leap) {
            var ld = leapDays(info);
            if (offset < ld) return { year: FIRST_YEAR + i, month: m, day: offset + 1, leap: true };
            offset -= ld;
          }
        }
      }
      offset -= yd;
    }
    return null;
  }

  return { fromSolar: fromSolar };
